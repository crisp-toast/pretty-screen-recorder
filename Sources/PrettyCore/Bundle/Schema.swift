    private static func f(_ p: String, _ t: String, _ d: String) -> Field { Field(path: p, type: t, doc: d) }

    static let known: Set<String> = {
        var s = Set<String>()
        for fl in fields {
            s.insert(fl.path)
            // Parents are known too.
            var parts = fl.path.split(separator: ".").map(String.init)
            while parts.count > 1 { parts.removeLast(); s.insert(parts.joined(separator: ".")) }
        }
        for top in ["source", "timeline", "zoom", "cursor", "keystrokes", "camera", "background", "layout", "frame", "motion", "captions", "audio", "export", "brand"] { s.insert(top) }
        return s
    }()

    /// Walks raw project JSON and reports unknown keys with suggestions.
    public static func unknownKeys(_ json: Any, prefix: String = "") -> [String] {
        var out: [String] = []
        if let d = json as? [String: Any] {
            for (k, v) in d {
                let path = prefix.isEmpty ? k : "\(prefix).\(k)"
                if !known.contains(path) {
                    let siblings = known.filter { $0.hasPrefix(prefix.isEmpty ? "" : prefix + ".") && $0.dropFirst(prefix.isEmpty ? 0 : prefix.count + 1).contains(".") == false }
                        .map { String($0.dropFirst(prefix.isEmpty ? 0 : prefix.count + 1)) }
                    let best = siblings.min { distance($0, k) < distance($1, k) }
                    let hint = best.map { distance($0, k) <= max(2, k.count / 3) ? " — did you mean '\($0)'?" : "" } ?? ""
                    out.append("unknown key '\(path)'\(hint)")
                    continue
                }
                out += unknownKeys(v, prefix: path)
            }
        } else if let a = json as? [Any] {
            for v in a { out += unknownKeys(v, prefix: prefix + "[]") }
        }
        return Array(Set(out)).sorted()
    }

    static func distance(_ a: String, _ b: String) -> Int {
        let a = Array(a.lowercased()), b = Array(b.lowercased())
        if a.isEmpty { return b.count }; if b.isEmpty { return a.count }
        var prev = Array(0...b.count)
        for i in 1...a.count {
            var cur = [i] + [Int](repeating: 0, count: b.count)
            for j in 1...b.count {
                cur[j] = min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] == b[j - 1] ? 0 : 1))
            }
            prev = cur
        }
        return prev[b.count]
    }

    /// Markdown-ish reference for agents.
    public static func reference() -> String {
        var defaults: [String: Any] = [:]
        if let data = try? JSONEncoder().encode(Project()), let obj = try? JSONSerialization.jsonObject(with: data) {
            flatten(obj, "", &defaults)
        }
        var lines: [String] = ["# project.json reference", "", "path | type | default | notes", "---|---|---|---"]
        for fl in fields {
            let d = defaults[fl.path].map { v -> String in
                if let s = v as? String { return "\"\(s)\"" }
                if let n = v as? NSNumber { return CFGetTypeID(n) == CFBooleanGetTypeID() ? (n.boolValue ? "true" : "false") : "\(n)" }
                if let a = v as? [Any] { return a.isEmpty ? "[]" : "[…]" }
                return ""
            } ?? ""
            lines.append("\(fl.path) | \(fl.type) | \(d) | \(fl.doc)")
        }
        return lines.joined(separator: "\n")
    }

    static func flatten(_ v: Any, _ prefix: String, _ out: inout [String: Any]) {
        if let d = v as? [String: Any] {
            for (k, x) in d { flatten(x, prefix.isEmpty ? k : "\(prefix).\(k)", &out) }
        } else { out[prefix] = v }
    }
